#pragma once

#include "Math/Vector2.h"
#include "Math/Vector3.h"
#include "Math/Vector4.h"

////////////////////////////////////////////////////////////////////////////////
// 스태틱 메시의 로컬 위치와 RGBA 색상, UV를 함께 보관하는 정점이다.
// 그래픽스 API 타입이나 GPU 자원을 보관하지 않는다.
////////////////////////////////////////////////////////////////////////////////
struct FStaticMeshVertex
{
	/** 메시 로컬 공간의 위치다. 기본값은 원점이다. */
	FVector3 position{};
	/** x / y / z / w를 빨강 / 초록 / 파랑 / 알파로 사용하는 선형 색상이다. 기본값은 불투명한 흰색이다. */
	FVector4 color{1.0f, 1.0f, 1.0f, 1.0f};
	/** x는 U, y는 V인 텍스처 좌표다. 기본값은 (0, 0)이다. */
	FVector2 uv{};
};
