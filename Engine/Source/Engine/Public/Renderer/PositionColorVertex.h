#pragma once

#include "Math/Vector3.h"

////////////////////////////////////////////////////////////////////////////////
// 로컬 위치와 RGBA 색상을 함께 보관하는 정점이다.
// 그래픽스 API 타입이나 GPU 자원을 보관하지 않는다.
////////////////////////////////////////////////////////////////////////////////
struct FPositionColorVertex
{
	/** 메시 로컬 공간의 위치다. 기본값은 원점이다. */
	FVector3 position{};
	/** 빨강 / 초록 / 파랑 / 알파 순서의 선형 색상이다. 기본값은 불투명한 흰색이다. */
	float color[4]{1.0f, 1.0f, 1.0f, 1.0f};
};
