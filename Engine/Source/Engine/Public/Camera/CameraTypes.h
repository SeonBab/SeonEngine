#pragma once

#include "Math/Rotator.h"
#include "Math/Vector3.h"

////////////////////////////////////////////////////////////////////////////////
// 카메라의 월드 위치, 회전과 수평 시야각을 값으로 보관하는 최소 시점 정보다.
// 기본값은 위치 / 회전 0과 수평 시야각 90도다. 객체 주소나 GPU 자원을 보관하지 않는다.
////////////////////////////////////////////////////////////////////////////////
struct FMinimalViewInfo
{
	/** 카메라의 월드 위치. 단위는 cm다. */
	FVector3 location{};
	/** 카메라의 월드 회전. 각도 단위는 도이며 SeonEngine의 축 규칙을 따른다. */
	FRotator rotation{};
	/** 원근 투영의 수평 시야각. 단위는 도다. */
	float fov = 90.0f;
};
