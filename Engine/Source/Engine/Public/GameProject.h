#pragma once

class FWorld;

////////////////////////////////////////////////////////////////////////////////
// 게임 프로젝트가 엔진에 제공하는 초기 월드 구성 계약이다.
// 구체 게임 타입과 콘텐츠는 게임 프로젝트에서 구현한다.
////////////////////////////////////////////////////////////////////////////////
class IGameProject
{
public:
	/** 인터페이스 포인터로 파괴해도 게임 구현의 소멸자를 호출한다. */
	virtual ~IGameProject() = default;

	/**
	 * 엔진이 준비한 월드를 빌려 게임의 초기 내용을 구성한다. 월드의 소유권은 가져오지 않는다.
	 * 성공하면 true, 실패하면 false를 반환하며 종료 정책은 호출자가 결정한다.
	 * 호출 시점 / 횟수와 실패 시 부분 구성 정리는 실제 연결 단계에서 정한다.
	 */
	[[nodiscard]] virtual bool InitializeWorld(FWorld& world) = 0;
};
