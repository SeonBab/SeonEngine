#pragma once

////////////////////////////////////////////////////////////////////////////////
// 4x4 행렬의 성분을 행 우선 순서로 보관한다. 기본값은 모두 0이다.
// 항등 설정·곱셈·역행렬 계산을 제공한다. Transform 변환은 별도 타입이 담당한다.
////////////////////////////////////////////////////////////////////////////////
struct FMatrix4
{
	/** m[행][열]로 접근하는 16개 성분. 인덱스는 0부터 시작한다. */
	float m[4][4]{};

	/** 모든 성분을 초기화해 대각선 1·나머지 0인 항등행렬로 설정한다. */
	void SetIdentity();

	/** 두 행렬의 곱을 반환한다. 원본은 유지하며 행 벡터 규칙에서 자신을 먼저, other를 나중에 적용한다. */
	[[nodiscard]] FMatrix4 operator*(const FMatrix4& other) const;

	/**
	 * 유한한 입력의 역행렬을 반환하며 원본은 유지한다.
	 * 행렬식이 0·비유한이거나 결과 성분이 비유한이면 항등행렬로 대체한다.
	 * NOTE: 대체값인 항등행렬은 실제 역행렬이나 계산 성공을 뜻하지 않는다.
	 */
	[[nodiscard]] FMatrix4 Inverse() const;
};
