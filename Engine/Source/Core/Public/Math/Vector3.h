#pragma once

////////////////////////////////////////////////////////////////////////////////
// 세 성분으로 위치, 방향, 크기 등을 표현하는 벡터다. 기본값은 모두 0이다.
// 공간 축은 X 왼쪽 / Y 위 / Z 앞이며, 위치로 사용할 때 단위는 cm다.
////////////////////////////////////////////////////////////////////////////////
struct FVector3
{
	/** X 성분. 공간 축의 양수 방향은 왼쪽이다. */
	float x = 0.0f;
	/** Y 성분. 공간 축의 양수 방향은 위쪽이다. */
	float y = 0.0f;
	/** Z 성분. 공간 축의 양수 방향은 앞쪽이다. */
	float z = 0.0f;
};
