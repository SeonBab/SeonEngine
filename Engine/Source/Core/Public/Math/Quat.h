#pragma once

struct FRotator;

////////////////////////////////////////////////////////////////////////////////
// 네 성분으로 3차원 회전을 표현하는 쿼터니언이다.
// 기본값 (0, 0, 0, 1)은 회전하지 않은 상태다. 각 성분은 축별 각도가 아니다.
////////////////////////////////////////////////////////////////////////////////
struct FQuat
{
	/** 쿼터니언의 벡터 부분 X 성분. */
	float x = 0.0f;
	/** 쿼터니언의 벡터 부분 Y 성분. */
	float y = 0.0f;
	/** 쿼터니언의 벡터 부분 Z 성분. */
	float z = 0.0f;
	/** 쿼터니언의 스칼라 부분. */
	float w = 1.0f;

	/**
	 * 유한한 단위 쿼터니언을 고정 축 X -> Y -> Z 순서의 도 단위 각도로 변환한다.
	 * pitch / roll은 [-180, 180], yaw는 [-90, 90]이다. 특이점의 별도 처리는 아직 없다.
	 * Unreal의 FQuat::Rotator()에 대응하는 변환 함수다. 축과 회전 규칙은 SeonEngine을 따른다.
	 */
	[[nodiscard]] FRotator ToRotator() const;
};
