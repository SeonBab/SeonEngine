#pragma once

////////////////////////////////////////////////////////////////////////////////
// 네 성분을 보관하는 벡터다. 기본값은 (0, 0, 0, 0)이다.
// 성분의 의미와 단위는 사용하는 곳에서 정한다.
////////////////////////////////////////////////////////////////////////////////
struct FVector4
{
	/** 첫 번째 성분이다. */
	float x = 0.0f;
	/** 두 번째 성분이다. */
	float y = 0.0f;
	/** 세 번째 성분이다. */
	float z = 0.0f;
	/** 네 번째 성분이다. 동차 좌표의 W나 색상의 알파 등 의미는 사용처에서 정한다. */
	float w = 0.0f;
};
