#pragma once

#include "Math/Quat.h"

////////////////////////////////////////////////////////////////////////////////
// pitch / yaw / roll을 도 단위로 보관하는 회전 데이터다.
// LUF의 X / Y / Z 양의 축에 오른손 법칙을 적용한다. 기본값은 회전 없음이다.
// 고정 기준 축 X(Left) -> Y(Up) -> Z(Forward) 순서로 회전을 해석한다.
// ToQuat으로 같은 회전을 나타내는 쿼터니언을 만든다.
////////////////////////////////////////////////////////////////////////////////
struct FRotator
{
	/** X축(왼쪽) 회전 각도. 기본 자세에서 양수는 앞 방향을 아래로 돌린다. */
	float pitch = 0.0f;
	/** Y축(위) 회전 각도. 기본 자세에서 양수는 앞 방향을 왼쪽으로 돌린다. */
	float yaw = 0.0f;
	/** Z축(앞) 회전 각도. +Z 쪽에서 원점을 볼 때 양수는 반시계 방향이다. */
	float roll = 0.0f;

	/**
	 * 유한한 도 단위 각도를 고정 축 X -> Y -> Z 순서의 정규화된 쿼터니언으로 변환한다.
	 * Unreal의 FRotator::Quaternion()에 대응하는 변환 함수다. 축과 회전 규칙은 SeonEngine을 따른다.
	 */
	[[nodiscard]] FQuat ToQuat() const;
};
