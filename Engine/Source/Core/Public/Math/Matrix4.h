#pragma once

////////////////////////////////////////////////////////////////////////////////
// 4x4 행렬의 성분을 행 우선 순서로 보관한다. 기본값은 모든 성분이 0이다.
////////////////////////////////////////////////////////////////////////////////
struct FMatrix4
{
	/** m[행][열]로 접근하는 16개 성분. 인덱스는 0부터 시작한다. */
	float m[4][4]{};

	/** 현재 행렬을 위치 / 회전 / 크기를 바꾸지 않는 항등행렬로 설정한다. */
	void SetIdentity();

	/** 두 행렬을 곱한 값을 반환한다. 원본을 변경하지 않는다. 행 벡터 규칙에서 자신을 먼저, other를 나중에 적용한다. */
	[[nodiscard]] FMatrix4 operator*(const FMatrix4& other) const;

	/**
	 * 유한한 성분의 행렬을 역변환한 값을 반환하며 원본은 변경하지 않는다.
	 * 역행렬을 만들 수 없으면 항등행렬로 대체한다. 대체값은 원래 변환의 역행렬을 뜻하지 않는다.
	 * 계산된 행렬식이 0 / 비유한이거나 역행렬 성분이 비유한이면 항등으로 대체한다. 카메라 호출 연결은 후속이다.
	 */
	[[nodiscard]] FMatrix4 Inverse() const;
};
