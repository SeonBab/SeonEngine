#pragma once

////////////////////////////////////////////////////////////////////////////////
// 모듈의 준비 / 종료 계약이다. 월드 구성이나 게임 세션 실행과는 별개다.
////////////////////////////////////////////////////////////////////////////////
class IModuleInterface
{
public:
	/** 기반 포인터로 파생 모듈을 파괴할 수 있다. ShutdownModule을 자동 호출하지 않는다. */
	virtual ~IModuleInterface() = default;

	/** 호출자가 모듈 준비 시 명시적으로 호출한다. 기본 구현은 비어 있다. */
	virtual void StartupModule() {}

	/** 호출자가 모듈 종료 시 명시적으로 호출한다. 기본 구현은 비어 있다. */
	virtual void ShutdownModule() {}
};
