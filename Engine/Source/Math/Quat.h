#pragma once

struct FRotator;

////////////////////////////////////////////////////////////////////////////////
// 네 float 성분으로 회전 데이터를 보관한다. 기본값 (0, 0, 0, 1)은 회전 없음이다.
// 각 성분은 축별 각도가 아니다. ToRotator는 정규화된 입력에서 도 단위 각도를 반환한다.
////////////////////////////////////////////////////////////////////////////////
struct FQuat
{
	float x = 0.0f;
	float y = 0.0f;
	float z = 0.0f;
	float w = 1.0f;

	/** 유한하고 정규화된 회전에서 도 단위 각도를 반환한다. pitch ±90도 근처에서는 roll을 0으로 둔다. */
	[[nodiscard]] FRotator ToRotator() const;
};
