#pragma once

////////////////////////////////////////////////////////////////////////////////
// 4x4 행렬의 성분을 행 우선 순서로 보관한다. 기본값은 모두 0이다.
// SetIdentity와 행렬 곱셈을 제공한다. Transform 변환은 아직 없다.
////////////////////////////////////////////////////////////////////////////////
struct FMatrix4
{
	/** m[행][열]로 접근하는 16개 성분. 인덱스는 0부터 시작한다. */
	float m[4][4]{};

	/** 모든 성분을 초기화해 대각선 1·나머지 0인 항등행렬로 설정한다. */
	void SetIdentity();

	/** 두 행렬의 곱을 반환한다. 원본은 유지하며 행 벡터 규칙에서 자신을 먼저, other를 나중에 적용한다. */
	[[nodiscard]] FMatrix4 operator*(const FMatrix4& other) const;
};
