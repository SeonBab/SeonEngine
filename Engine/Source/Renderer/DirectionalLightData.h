#pragma once

#include "Core/Math/Vector3.h"

////////////////////////////////////////////////////////////////////////////////
// 방향광 하나의 방향, 선형 RGB 색, 밝기 배율을 값으로 전달하는 CPU 데이터다.
// 기본값은 +Z 진행 방향, 흰색, 세기 1이며 광원의 존재나 Scene 등록을 뜻하지 않는다.
// 액터, 컴포넌트, GPU 자원을 소유하지 않으며 값 검사나 정규화는 수행하지 않는다.
////////////////////////////////////////////////////////////////////////////////
struct FDirectionalLightData
{
	/** 빛이 진행하는 월드 공간의 단위 방향. 표면에서 광원을 향하는 방향은 이 값의 반대다. */
	FVector3 direction{0.0f, 0.0f, 1.0f};

	/** 유한한 0 이상 성분의 선형 RGB. x, y, z는 R, G, B이며 알파나 sRGB 변환은 없다. 1 초과도 허용한다. */
	FVector3 lightColor{1.0f, 1.0f, 1.0f};

	/** 색에 곱할 유한한 0 이상의 밝기 배율. 0은 빛 없음, 1은 기본 밝기이며 lux 단위가 아니다. */
	float intensity = 1.0f;
};
