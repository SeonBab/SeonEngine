#pragma once

#include "Renderer/ModelData.h"

#include <filesystem>

////////////////////////////////////////////////////////////////////////////////
// Assimp가 읽은 정적 모델을 엔진 소유 CPU 데이터로 옮긴다.
// 외부 파서 자료형을 노출하지 않으며 GPU 자원이나 Actor를 생성하지 않는다.
////////////////////////////////////////////////////////////////////////////////
struct FModelLoader
{
	/**
	 * 상대 경로는 현재 작업 폴더 기준이다. 삼각형화·정점 병합·왼손 변환을 적용하고
	 * 메시별 위치/법선/첫 UV, 기본 색상/외부 텍스처 경로, 노드 계층을 보관한다.
	 * 추가 단위 스케일은 적용하지 않는다. 읽기 후 법선 누락·뼈·애니메이션·모프·내장 텍스처는 거부한다.
	 * 일반적인 읽기·지원 범위 검사 실패는 로그와 false를 반환하며 기존 outModel을 유지한다.
	 * 이미지 디코딩·텍스처 파일 존재 확인은 하지 않으며 메모리 부족의 false 복구는 보장하지 않는다.
	 */
	[[nodiscard]] static bool LoadModelFile(const std::filesystem::path& path, FModelData& outModel);
};
