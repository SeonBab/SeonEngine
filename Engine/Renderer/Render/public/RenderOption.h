#endif

#if RENDER_DEBUG_OUTPUT_MODE != RENDER_DEBUG_OUTPUT_ENABLE && RENDER_DEBUG_OUTPUT_MODE != RENDER_DEBUG_OUTPUT_DISABLE
#error "RENDER_DEBUG_OUTPUT_MODE 값 오류"
#endif



#ifndef RENDER_REPORT_SEND_MODE
#warning "RENDER_REPORT_SEND_MODE 값 미정의 (DISABLE로 취급)"
#define RENDER_REPORT_SEND_MODE RENDER_REPORT_SEND_DISABLE
#endif

#if RENDER_REPORT_SEND_MODE != RENDER_REPORT_SEND_ENABLE && RENDER_REPORT_SEND_MODE != RENDER_REPORT_SEND_DISABLE
#error "RENDER_REPORT_SEND_MODE 값 오류"
#endif



